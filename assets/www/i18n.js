/* ---------- the engine ---------- */
/* Read the saved choice here rather than through the app's LS helper: this file
   loads before app.js, so LS does not exist yet. */
let UI_LANG = (() => {
  try { const v = localStorage.getItem('onegit.lang'); return v === null ? 'auto' : JSON.parse(v); }
  catch (e) { return 'auto'; }
})();

/* the phone's own language, via the device bridge */
function systemLang() {
  try {
    if (window.OneGit && window.OneGit.deviceLang) {
      const tag = window.OneGit.deviceLang();
      if (tag) return String(tag);
    }
  } catch (e) { }
  try { return String(navigator.language || 'en'); } catch (e) { return 'en'; }
}
function systemLangs() {
  try {
    if (window.OneGit && window.OneGit.deviceLangs) {
      const a = JSON.parse(window.OneGit.deviceLangs() || '[]');
      if (Array.isArray(a) && a.length) return a;
    }
  } catch (e) { }
  return [systemLang()];
}

/* which language is actually in use right now */
function langCode() {
  if (UI_LANG && UI_LANG !== 'auto') return STRINGS[UI_LANG] ? UI_LANG : 'en';
  for (const tag of systemLangs()) {
    const base = String(tag).toLowerCase().split('-')[0];
    if (STRINGS[base]) return base;
  }
  return 'en';
}
/* one string; anything not translated falls back to English, never to a blank */
function i18n(key) {
  const c = langCode();
  const tbl = STRINGS[c] || {};
  if (tbl[key] !== undefined) return tbl[key];
  return STRINGS.en[key] !== undefined ? STRINGS.en[key] : key;
}
function langName(code) {
  const l = LANGS.find(x => x[0] === code);
  return l ? l[1] : code;
}
/* languages that have real words, not an English fallback */
function langTranslated(code) { return !!STRINGS[code] && code !== 'en'; }
/* fill anything marked data-i18n, and set the document language */
function applyLang() {
  try { document.documentElement.lang = langCode(); } catch (e) { }
  try {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const k = el.getAttribute('data-i18n');
      const v = i18n(k);
      if (v && el.textContent !== v) el.textContent = v;
    });
  } catch (e) { }
}
